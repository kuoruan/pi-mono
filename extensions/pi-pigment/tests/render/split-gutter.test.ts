describe("split gutter width (paired rows pull far-away numbers into view)", () => {
  it("sizes the gutter to the visible rows' own numbers, not any line-prefix window", async () => {
    resetPaletteForTest();
    const palette = resolveDiffPalette(buildFakeTheme());
    const diff = parseDiff(OLD_FILE.join("\n") + "\n", NEW_FILE.join("\n") + "\n");
    const out = await renderSplit({
      diff,
      language: undefined,
      maxLines: 113,
      width: 160,
      palette,
      indicator: "bar",
    });
    const lines = plain(out).split("\n");
    // The deepest visible number renders — and every content row
    // measures the full render width (160): the sheared row measured
    // 161 (its "101" overflowed a two-digit gutter's number cell and
    // pushed the right half one column late).
    expect(lines.some((l) => /\b101\b/.test(l))).toBe(true);
    const contentRows = lines.filter((l) => /[0-9]/.test(l) && !l.includes("..."));
    const widths = [...new Set(contentRows.map((l) => l.length))];
    expect(widths).toEqual([160]);
  });
});
